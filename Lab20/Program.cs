using System;

namespace PracticalWork20
{
    // ==========================================
    // === ІНТЕРФЕЙСИ З ОДНАКОВИМИ МЕТОДАМИ ===
    // ==========================================

    public interface ILeft
    {
        void Execute();
    }

    public interface IRight
    {
        void Execute();
    }

    // ==========================================
    // === РЕАЛІЗАЦІЯ КЛАСУ ЧЕРЕЗ ЯВНУ РЕАЛІЗАЦІЮ ===
    // ==========================================

    public class Controller : ILeft, IRight
    {
        // Явна реалізація методу для інтерфейсу ILeft
        void ILeft.Execute()
        {
            Console.WriteLine("[ILeft] Виконано дію лівого інтерфейсу.");
        }

        // Явна реалізація методу для інтерфейсу IRight
        void IRight.Execute()
        {
            Console.WriteLine("[IRight] Виконано дію правого інтерфейсу.");
        }
    }

    // ==========================================
    // === ТОЧКА ВХОДУ (ГОЛОВНИЙ КЛАС) ===
    // ==========================================
    class Program
    {
        // Здесь добавлены квадратные скобки [] для корректного массива строк
        static void Main(string[] args)
        {
            // ------------------------------------------
            // ЧАСТИНА 1: ЗАГАЛЬНЕ ЗАВДАННЯ
            // ------------------------------------------
            Console.WriteLine("=== ЧАСТИНА 1: ЗАГАЛЬНЕ ЗАВДАННЯ ===");

            // Створюємо екземпляр класу Controller
            Controller controller = new Controller();

            // Виклик методів через приведення типу до відповідних інтерфейсів
            Console.WriteLine("--- Виклик методу через інтерфейс ILeft ---");
            ILeft leftRef = (ILeft)controller;
            leftRef.Execute();

            Console.WriteLine("\n--- Виклик методу через інтерфейс IRight ---");
            IRight rightRef = (IRight)controller;
            rightRef.Execute();

            // ------------------------------------------
            // ЧАСТИНА 2: ДОМАШНЄ ЗАВДАННЯ
            // ------------------------------------------
            Console.WriteLine("\n=== ЧАСТИНА 2: ДОМАШНЄ ЗАВДАННЯ ===");
            Console.WriteLine("Дослідження доступності явно реалізованих методів через звичайну змінну класу:");
            
            // Спроба викликати метод Execute безпосередньо через змінну 'controller':
            // ЦЕЙ КОД ЗАКОМЕНТОВАНО, ТОМУ ЩО ВІН ВИКЛИКАЄ ПОМИЛКУ КОМПІЛЯЦІЇ.
            /*
            controller.Execute(); 
            */
            
            // Фіксуємо правило та текст помилки для звіту
            Console.WriteLine("-> Результат: Прямий виклик 'controller.Execute()' НЕМОЖЛИВИЙ.");
            Console.WriteLine("-> Помилка компіляції: CS1061 'Controller' does not contain a definition for 'Execute'...");
            Console.WriteLine("\n[ПРАВИЛО ДОСТУПНОСТІ (ДЗ)]:");
            Console.WriteLine("Явно реалізовані методи інтерфейсу є ПРИХОВАНИМИ (private) для екземпляра класу.");
            Console.WriteLine("Вони не входять у відкритий інтерфейс самого класу, тому викликати їх можна");
            Console.WriteLine("ВИКЛЮЧНО після приведення об'єкта до типу відповідного інтерфейсу.");
        }
    }
}
