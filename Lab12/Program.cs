using System;

namespace OOP_Lab12
{
    // ==========================================================================
    // БАЗОВИЙ КЛАС: Транспортний засіб (Vehicle)
    // ==========================================================================
    public class Vehicle
    {
        // Захищене поле швидкости - доступне всередині цього класу та в усіх похідних
        protected double speed;

        public Vehicle(double speed)
        {
            this.speed = speed;
        }

        // Звичайний (не віртуальний) метод для заміщення
        public void Start()
        {
            Console.WriteLine("Транспортний засіб починає рух зі швидкістю " + speed + " км/год. (Виклик з базового класу)");
        }
    }

    // ==========================================================================
    // ПОХІДНИЙ КЛАС: Автомобіль (Car)
    // ==========================================================================
    public class Car : Vehicle
    {
        public string Model { get; set; }

        public Car(string model, double speed) : base(speed)
        {
            Model = model;
        }

        // ЗАГАЛЬНЕ ЗАВДАННЯ: Заміщення методу Start() за допомогою модифікатора new
        public new void Start()
        {
            // Маємо прямий доступ до захищеного поля speed батьківського класу
            Console.WriteLine("🚗 Автомобіль " + Model + " заводить двигун і розганяється до " + speed + " км/год! (Виклик з похідного класу)");
        }
    }

    class Program
    {
        static void Main(string[] args)
        {
            Console.WriteLine("==========================================================================");
            Console.WriteLine(" ОБ'ЄКТНО-ОРІЄНТОВАНЕ ПРОГРАМУВАННЯ // ПРАКТИЧНА РОБОТА №12: METHOD HIDING");
            Console.WriteLine("==========================================================================");

            // 1. Тестування загального завдання
            Console.WriteLine("\n🔵 --- Створення об'єкта похідного класу Car ---");
            Car myCar = new Car("Tesla Model 3", 120);
            myCar.Start(); // Викличе заміщений метод з класу Car

            // 2. Тестування домашнього завдання (Дослідження заміщення через базове посилання)
            Console.WriteLine("\n📊 --- ДОМАШНЄ ЗАВДАННЯ: Виклик через посилання на базовий клас ---");
            
            // Зберігаємо посилання на об'єкт Car у змінну базового типу Vehicle
            Vehicle vehicleReference = myCar;

            Console.Write("Виклик Start() через змінну типу Vehicle: ");
            vehicleReference.Start(); 
            // При заміщенні (new) тип змінної визначає, який метод виконається. 
            // Оскільки тип змінної Vehicle, запуститься оригінальний метод з Vehicle, а не з Car!

            Console.WriteLine("\n==========================================================================");
        }
    }
}
